"""Write the Markdown source of the Word speech script from script.json (run from the repo root, then pandoc)."""
import json, re, sys
ver = sys.argv[1] if len(sys.argv) > 1 else "v2"
S = json.load(open("figures/deck/script.json", encoding="utf-8"))
tot = {}
for s in S:
    m, sec = map(int, s["time"].split(":")); tot[s["speaker"]] = tot.get(s["speaker"], 0) + m * 60 + sec
words = sum(len(re.sub(r"【[^】]*】", "", s["en"]).split()) for s in S)
cue = lambda t: re.sub(r"【([^】]*)】", r"*【\1】*", t)
parts = {1: "开场、比赛背景、越跑越慢", 2: "堵在门口（花一周写监测程序看回放）、前人工作、我们试过的全部办法（提升都不大）、拥塞监测程序（不管怎么改选路，拥塞总在同几处）",
         3: "技术部分：模型和天花板（为什么改路线没用）、我们的车和计算机网络、道路交通哪里不同（所以要自己想出新算法 DoorFlow）、名额（每道门一个窗口、像 BBR 一样全局调控、按门按方向数）、门口规则（一次一个方向、缓冲区多大、门口的队列调度）、执行器修复",
         4: "伪代码、最难的部分和拥堵回放演示、随机门新图测试、两个兜底、结果、哪些起作用、五条经验（DoorFlow 为什么是这个样子）、结论"}
L = ["# SEEM5910 演讲稿与幻灯片（四人，15 分钟）", "",
     f"这份 Word 是幻灯片 `SEEM5910_演讲PPT_{ver}.pptx` 的讲稿版。每页依次是：幻灯片图片；讲者、时长和配图；**提示卡**（几个要点，看一眼就能接着讲）；讲稿（**每一段英文下面紧跟它的中文**，英文用简单词和短句，方便记、讲得快也好懂）。",
     "讲稿里的 *【……】* 是动作提示，告诉你这时指图上哪里；**加粗**的是这一页要讲准的关键句和数字。**每页幻灯片上都印着这一页的英文讲稿**（去掉了动作提示），可以照着读；幻灯片备注栏里还有提示卡和中英文讲稿。", "",
     "## 分工和时间", "", "| 讲者 | 负责的页 | 内容 | 时长 |", "|---|---|---|---|"]
for k in sorted(tot):
    pages = [str(s["n"]) for s in S if s["speaker"] == k]
    L.append(f"| 讲者 {k} | 第 {pages[0]}–{pages[-1]} 页 | {parts[k]} | {tot[k] // 60}:{tot[k] % 60:02d} |")
T = sum(tot.values())
L += [f"| 合计 | {len(S)} 页 | | {T // 60}:{T % 60:02d} |", "",
      "讲者 3 负责模型、名额、门口规则和执行器修复这些主要的技术内容，所以时间最长；讲者 1、2 讲问题和想法；讲者 4 讲伪代码、最难的部分和演示、随机门测试和两个兜底、结果和结论。交接处的讲稿里都写好了交接语。", "",
      f"英文讲稿共 {words} 词（不算动作提示）。15 分钟讲完，平均每分钟要讲约 {words / 15:.0f} 词，时间比较紧：照着幻灯片读时语速不要放太慢，指图时少停。各页时长按每页的词数分配。", ""]
for s in S:
    figs = "；".join(s["figs"]) if s["figs"] else "无（文字和数字卡片）"
    L += [f"## 第 {s['n']} 页　{s['title']}", "", f"![第 {s['n']} 页](figures/deck/slides/slide-{s['n']:02d}.png)", "",
          f"**讲者 {s['speaker']}　·　{s['time']}　·　配图：{figs}**", "", "**提示卡**", ""]
    L += [f"- {h}" for h in s["hints"]]
    L += ["", "**讲稿**", ""]
    for g in s["segs"]:
        L += [cue(g["en"]), "", "> " + cue(g["zh"]), ""]
L += ["## 说明", "", "- 图号指《全文简明版（中文）v11》里的图号；幻灯片里的图和报告共用，图中文字都是英文。",
      "- 每页幻灯片上的英文讲稿和这份 Word 里的英文讲稿都由 `figures/deck/script.json` 生成，字完全一样；幻灯片上的字号按每页字数自动定在 14–20 号。",
      "- 第 7、10、11、13、14、15、16、18、22 页用的是演讲专用图：第 10 页窗口大小原理图、第 11 页 BBR 控制环与 DoorFlow 对照图、第 15 页门利用率曲线（`make_principle_figs.py`）；第 13、14 页是门口规则详图的两半（A；B 和 C），由 `make_crops.py` 从 `fig_door_rule_deck.png` 切出；第 16 页执行器修复的实测和第 22 页逐项拿掉与加上（`make_deck_ablation.py`）；第 7 页拥塞监测程序截图、第 18 页回放动图（`figures/deck/demo/`）。第 6 页的全部尝试总表、第 9 页的对比表和第 23 页的五条经验直接做在幻灯片上。",
      "- 第 9 页的对比表（我们的车 / 计算机网络 / 道路交通）：阴影格表示和我们的车不一样；计算机网络这一列六行都不一样，道路交通这一列前两行（车不能丢、等着的车占地方）一样、后四行不一样，所以两边的算法都不能直接照搬。",
      "- 第 10 页从问题出发推出每道门的窗口（名额）：路上的车数 = 过门速率 × 路程时间。讲的时候直接用门 6 的数：每个方向每 38.5 拍进一台（每 500 拍 13 台），走到门口约 550 拍（2.23 × 247，算上故障），所以路上约 550 ÷ 38.5 ≈ 14.3 台，窗口取 15。这条计数规律在排队论里叫 Little 定律（1961 年），不是我们发现的；讲稿里不提名字、也不说成是我们发现的，第 10 页的图注里写了它的名字，老师问起可以直接说。",
      "- 第 11 页的 BBR 是谷歌的服务器决定数据发多快的方法；我们借的是它“只看测到的最大送达速率和最短时延”的思路。第 51 轮在模型漏掉的窄处试了 BBR 式上限，总体 +0.08% [−0.32, +0.47]，所以保留固定名额。",
      "- 第 14 页的缓冲区大小：下限用公式算，同方向每 9 拍出来一台、走一步 3 拍，⌈9 ÷ 3⌉ = 3 格（`netmac.cpp` 第 59–62 行注释，第 57 轮）；再在 12 个开发实例上实测 1、2、3、4、6 格（v58 附录 H）；3 格的确认测试 −2.64%、堵死局 11 → 29（第 54–57 轮），所以用 4 格。",
      "- 第 15 页的换向实验：按固定时间表换向 −4.98%、−6.43%（第 6 页表里的 802.1Qbv）；把“每轮最多放 80 步”换成“走空再换”，总体 +1.11%，其中官方房间图 −0.4%、新生成的房间图 +1.9%（第 46 轮）。",
      "- 第 7 页的截图是拥塞监测程序 `figures/deck/demo/congestion_monitor.html`（第 3000 拍）：同一张官方房间图、250 台车、同一组种子（9700 / 101），都不控制门，只换选路（冠军的选路、HN-SPF 链路代价、Fortz–Thorup 权重），各跑一局；右边“Where jams happen”是每道门在整局里堵着的时间比例，门 6 在三种选路下都是 91%–94%。完成数 609 / 435 / 612 是这一局的结果；HN-SPF 和 Fortz–Thorup 在报告里的 −25.88% 和 −0.29% 是多张图、加在当时完整方法上的测试，和这一局口径不同。数字见 `figures/deck/demo/monitor_stats.json`。",
      "- 第 18 页的回放动图来自 `figures/deck/demo/`：`doorflow_demo.html` 用浏览器打开就能看（两边同步播放，拥堵的车和门自动变红，可拖动时间轴、跳到第 3000 拍）；609 和 1130 是这一局（官方房间图 250 台，种子 9700 / 101）的完成数，不是平均值。复现步骤写在 `run_demo.py` 和 `build_demo.py` 开头。",
      "- 第 19、20 页用同一张换图测试图：第 19 页讲第一栏（完整方法对比底座），第 20 页讲第二、三栏（拿掉全图上限 / 拿掉看门狗）。",
      "- 讲稿里的数字都取自全文简明版，出处见那份文档末尾的数字来源表。",
      "- 幻灯片由 `figures/deck/build_deck.js` 生成，讲稿来自 `figures/deck/script.json`，这份 Word 由 `figures/deck/make_script_doc.py` 生成；改讲稿时改 script.json，再重新生成两份。", ""]
open("figures/deck/演讲稿_源稿.md", "w", encoding="utf-8").write("\n".join(L))
print(words, tot)
